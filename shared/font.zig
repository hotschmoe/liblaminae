//------------------------------------------------------------------------------
// font - 8x16 bitmap font + glyph blitter
//
// SHARED between kernel and user space (src/shared/, synced to lib/shared/).
// The kernel framebuffer console (src/kernel/console/fbcon.zig) and the T1
// user-space console (lib/man/fbcon.zig) blit the same glyphs -- one font,
// one blitter, zero drift. Pure vocabulary: glyph data + writes into a
// caller-supplied linear framebuffer. No syscalls, no allocation.
//
// Coverage is printable ASCII 0x20..0x7E (95 glyphs). Each glyph is a
// 16-byte bitmap, one byte per row, MSB (0x80) = leftmost pixel, a set bit
// = foreground. The cell advance is a fixed 8 px, so callers form a simple
// character grid (e.g. 800x600 -> 100x37 cells).
//
// The framebuffer is addressed as [*]volatile u32 with a row stride in
// pixels; the pixel format is whatever the caller's display expects (ramfb
// uses XRGB8888, so a pixel is 0x00RRGGBB). drawChar / drawString do NOT
// bounds-check against the framebuffer extent -- the caller must keep
// (x+8, y+16) inside the surface.
//------------------------------------------------------------------------------

/// Tier marker consumed by the liblaminae audit when re-exported to user
/// space; meaningless to the kernel but harmless.
pub const tier: u8 = 1;

pub const GLYPH_W: u32 = 8;
pub const GLYPH_H: u32 = 16;

/// First and last code point with a glyph. Anything outside renders blank.
const FIRST: u8 = 0x20;
const LAST: u8 = 0x7E;

/// Returns one bitmap row of the glyph for `ch`. Out-of-range code points
/// and rows render as blank (0).
pub fn glyphRow(ch: u8, row: u32) u8 {
    if (ch < FIRST or ch > LAST or row >= GLYPH_H) return 0;
    return glyphs[ch - FIRST][row];
}

/// Blit one glyph at pixel (x, y). Every cell pixel is written -- set bits
/// take `fg`, clear bits take `bg` -- so a redraw fully overwrites the cell
/// (no transparency, which is what a text console wants).
pub fn drawChar(fb: [*]volatile u32, stride_px: u32, x: u32, y: u32, ch: u8, fg: u32, bg: u32) void {
    var row: u32 = 0;
    while (row < GLYPH_H) : (row += 1) {
        const bits = glyphRow(ch, row);
        const base = (y + row) * stride_px + x;
        var col: u32 = 0;
        while (col < GLYPH_W) : (col += 1) {
            const on = (bits & (@as(u8, 0x80) >> @intCast(col))) != 0;
            fb[base + col] = if (on) fg else bg;
        }
    }
}

/// Blit a string left-to-right starting at (x, y). No wrapping or newline
/// handling -- one cell per byte. Returns the x past the last cell.
pub fn drawString(fb: [*]volatile u32, stride_px: u32, x: u32, y: u32, s: []const u8, fg: u32, bg: u32) u32 {
    var px = x;
    for (s) |c| {
        drawChar(fb, stride_px, px, y, c, fg, bg);
        px += GLYPH_W;
    }
    return px;
}

